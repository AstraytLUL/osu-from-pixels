"""Tables 1-3 and Figures 1-3 of the RL brief, generated from the saved raw evaluation files only.

    python -m rl.report        # -> rl/results/tables.md, rl/results/fig{1,2,3}_*.png

Inputs: rl/results/exp1.csv, exp2.csv (+ .offsets.jsonl) written by rl/evaluate.py, and the learning
curves rl/runs/<run>/curve.csv written by rl/ppo.py. Per condition and seed, a metric is first
averaged over maps (every map weighs the same), then reported as mean ± sd over seeds (n stated).
"""
import csv
import glob
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

from rl.evaluate import map_list

R = Path("rl/results")
METRICS = [("accuracy", "Accuracy %", 100), ("count_miss", "Misses", 1), ("miss_circle_position", "Circle misses: position", 1),
           ("miss_circle_click", "Circle misses: click/timing", 1), ("max_combo_ratio", "Max combo / full", 100),
           ("slider_breaks", "Slider breaks", 1), ("unstable_rate", "UR", 1), ("mean_hit_error", "Mean hit error ms", 1)]


def rows(path: Path) -> list[dict]:
    return list(csv.DictReader(path.open(newline=""))) if path.exists() else []


def per_seed(rs: list[dict], metric: str) -> list[float]:
    """Map-averaged value of `metric` per seed."""
    by = defaultdict(list)
    for r in rs:
        if r[metric] not in ("", "None"):
            by[r["seed"]].append(float(r[metric]))
    return [float(np.mean(v)) for v in by.values()]


def fmt(values: list[float], scale: float) -> str:
    if not values:
        return "–"
    v = np.array(values) * scale
    return f"{v.mean():.2f}" if len(v) == 1 else f"{v.mean():.2f} ± {v.std(ddof=1):.2f}"


def table(groups: list[tuple[str, list[dict]]]) -> str:
    head = "| Condition | n seeds | " + " | ".join(m[1] for m in METRICS) + " |"
    lines = [head, "|" + "---|" * (len(METRICS) + 2)]
    for name, rs in groups:
        seeds = len({r["seed"] for r in rs})
        lines.append(f"| {name} | {seeds} | " + " | ".join(fmt(per_seed(rs, m), s) for m, _, s in METRICS) + " |")
    return "\n".join(lines)


def select(rs, label_re: str, mods: str, maps=None):
    return [r for r in rs if re.fullmatch(label_re, r["label"]) and r["mods"] == mods
            and (maps is None or int(r["beatmap_id"]) in maps)]


def curves(pattern: str, mods: str):
    """{seed: [(steps, accuracy %, misses)]} from the runs' curve.csv files."""
    out = {}
    for path in sorted(glob.glob(pattern)):
        seed = re.search(r"seed(\d+)", path).group(1)
        pts = defaultdict(list)
        for r in rows(Path(path)):
            if r["mods"] == mods:
                pts[int(r["label"].split("_")[1])].append((float(r["accuracy"]), float(r["count_miss"])))
        out[seed] = [(s, 100 * np.mean([a for a, _ in v]), np.mean([m for _, m in v])) for s, v in sorted(pts.items())]
    return out


TRANSFER_STYLES = {"jumps": [4967007, 4235907, 4669413, 3100786, 4618179],
                   "streams": [2654458, 4203275, 4798513, 4904540], "tech": [1785659]}   # rl/maps.yaml


def transfer_table(rs: list[dict]) -> list[str]:
    """Table 4 (addition): accuracy % on the hard test maps (rl/maps.yaml exp2_transfer) grouped by
    style; each specialist as the change vs BC, mean ± sd over its 3 seeds (per seed: mean over the
    group's maps)."""
    base = {int(r["beatmap_id"]): float(r["accuracy"]) for r in rs if r["label"] == "exp2_A"}
    if not base:
        return []
    groups = list(TRANSFER_STYLES.items()) + [("all", sum(TRANSFER_STYLES.values(), []))]
    lines = ["## Table 4. Experiment 2 transfer (addition): the hard test maps (8-9 stars), NoMod", "",
             "BC: accuracy %. Specialists: change vs BC in pp, mean ± sd over 3 seeds.", "",
             "| Policy | " + " | ".join(f"{st} ({len(ids)} maps)" for st, ids in groups) + " |",
             "|" + "---|" * (len(groups) + 1),
             "| A: BC | " + " | ".join(f"{100 * np.mean([base[b] for b in ids]):.2f}" for _, ids in groups) + " |"]
    for bid, cat in ((4952940, "jump"), (555797, "stream"), (4377326, "tech")):
        cells = []
        for _, ids in groups:
            by = defaultdict(list)
            for r in rs:
                if r["label"] == f"exp2_B_{bid}" and int(r["beatmap_id"]) in ids:
                    by[r["seed"]].append(float(r["accuracy"]) - base[int(r["beatmap_id"])])
            v = 100 * np.array([np.mean(x) for x in by.values()])
            cells.append("–" if not len(v) else f"{v.mean():+.2f} ± {v.std(ddof=1):.2f}" if len(v) > 1 else f"{v.mean():+.2f}")
        lines.append(f"| B: {cat} specialist ({bid}) | " + " | ".join(cells) + " |")
    return lines + [""]


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    e1, e2 = rows(R / "exp1.csv"), rows(R / "exp2.csv")
    md = ["# RL results tables (generated by `python -m rl.report`; do not edit by hand)", ""]
    groups = [("A: BC zero-shot", "exp1_A"), ("B: BC + PPO on HD", "exp1_B"), ("C: BC + supervised HD", "exp1_C"),
              # additions beyond the brief (rl/RESULTS.md); rows appear once their results exist
              ("D: C + PPO on HD and NoMod (addition)", "exp1_D"),
              ("C-mix: BC + supervised HD and NoMod (addition)", "exp1_Cmix")]
    groups = [g for g in groups if g[1] in {"exp1_A", "exp1_B", "exp1_C"} or select(e1, g[1], "HD")]
    md += ["## Table 1. Experiment 1 on the held-out maps with HD", "",
           table([(n, select(e1, l, "HD")) for n, l in groups]), "",
           "## Table 2. Experiment 1 forgetting: the same models on the held-out maps, NoMod", "",
           table([(n, select(e1, l, "NM")) for n, l in groups]), ""]
    heldout = set(map_list("heldout"))
    md += ["## Table 3. Experiment 2 (specialisation: trained and evaluated on the same map, NoMod)", ""]
    for bid, cat in ((4952940, "jump"), (555797, "stream"), (4377326, "tech")):
        md += [f"**{cat} {bid}**", "",
               table([("A: BC, this map", select(e2, "exp2_A", "NM", {bid})),
                      ("B: BC + PPO on this map, this map", select(e2, f"exp2_B_{bid}", "NM", {bid})),
                      ("A: BC, held-out maps", select(e1, "exp1_A", "NM", heldout)),
                      ("B: held-out maps (forgetting)", select(e2, f"exp2_B_{bid}", "NM", heldout))]), ""]
    md += transfer_table(rows(R / "exp2_transfer.csv"))
    (R / "tables.md").write_text("\n".join(md), encoding="utf-8")

    # Figure 1: Experiment 1 learning curves (held-out HD), A and C as reference lines
    fig, ax = plt.subplots(1, 2, figsize=(10, 3.6))
    cs = curves("rl/runs/exp1_B_seed*/curve.csv", "HD")
    for seed, pts in cs.items():
        if pts:
            s, a, m = zip(*pts)
            ax[0].plot(s, a, lw=1, alpha=.8, label=f"B seed {seed}")
            ax[1].plot(s, m, lw=1, alpha=.8)
    for name, label, style in (("A (BC zero-shot)", "exp1_A", "--"), ("C (supervised HD)", "exp1_C", ":")):
        rs = select(e1, label, "HD")
        if rs:
            ax[0].axhline(100 * np.mean(per_seed(rs, "accuracy")), ls=style, c="k", lw=1, label=name)
            ax[1].axhline(np.mean(per_seed(rs, "count_miss")), ls=style, c="k", lw=1)
    ax[0].set(xlabel="agent steps", ylabel="accuracy % (held-out, HD)")
    ax[1].set(xlabel="agent steps", ylabel="misses per map (held-out, HD)")
    ax[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(R / "fig1_exp1_curves.png", dpi=130)

    # Figure 2: hit-error histograms (held-out, HD), with BC on NoMod for reference
    offs = defaultdict(list)
    p = R / "exp1.offsets.jsonl"
    for line in (p.read_text().splitlines() if p.exists() else []):
        d = json.loads(line)
        offs[(d["label"], d["mods"])] += d["offsets"]
    fig, ax = plt.subplots(figsize=(6, 3.6))
    bins = np.arange(-150, 151, 5)
    for key, name in ((("exp1_A", "NM"), "BC, NoMod"), (("exp1_A", "HD"), "A: BC, HD"),
                      (("exp1_B", "HD"), "B: PPO, HD"), (("exp1_C", "HD"), "C: supervised, HD")):
        if offs[key]:
            ax.hist(offs[key], bins=bins, histtype="step", density=True, label=f"{name} (n={len(offs[key])})")
    ax.set(xlabel="hit error, ms (< 0 early)", ylabel="density")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(R / "fig2_exp1_hit_errors.png", dpi=130)

    # Figure 3: Experiment 2 learning curves per map
    fig, ax = plt.subplots(1, 3, figsize=(13, 3.6))
    for a, (bid, cat) in zip(ax, ((4952940, "jump"), (555797, "stream"), (4377326, "tech"))):
        for seed, pts in curves(f"rl/runs/exp2_B_{bid}_seed*/curve.csv", "NM").items():
            if pts:
                s, acc, _ = zip(*pts)
                a.plot(s, acc, lw=1, label=f"seed {seed}")
        base = select(e2, "exp2_A", "NM", {bid})
        if base:
            a.axhline(100 * float(base[0]["accuracy"]), ls="--", c="k", lw=1, label="A (BC)")
        a.set(title=f"{cat} {bid}", xlabel="agent steps", ylabel="accuracy % (this map)")
        a.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(R / "fig3_exp2_curves.png", dpi=130)

    # Figure 4 (addition): condition D learning curves, held-out HD and NoMod, with C and C-mix
    ds = {m: curves("rl/runs/exp1_D_seed*/curve.csv", m) for m in ("HD", "NM")}
    if any(ds["HD"].values()):
        fig, ax = plt.subplots(1, 2, figsize=(10, 3.6))
        for a, m in zip(ax, ("HD", "NM")):
            for seed, pts in ds[m].items():
                if pts:
                    s_, acc, _ = zip(*pts)
                    a.plot(s_, acc, lw=1, label=f"D seed {seed}")
            for name, label, style in (("A (BC)", "exp1_A", "--"), ("C (supervised HD)", "exp1_C", ":"),
                                       ("C-mix", "exp1_Cmix", "-.")):
                rs = select(e1, label, m)
                if rs:
                    a.axhline(100 * np.mean(per_seed(rs, "accuracy")), ls=style, c="k", lw=1, label=name)
            a.set(xlabel="agent steps", ylabel=f"accuracy % (held-out, {'HD' if m == 'HD' else 'NoMod'})")
            a.legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(R / "fig4_exp1_D_curves.png", dpi=130)
    print(f"wrote {R / 'tables.md'} and figures")


if __name__ == "__main__":
    main()
